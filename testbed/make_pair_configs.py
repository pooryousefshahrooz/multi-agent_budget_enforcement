# Per-agent limits do not compose: a task with k subtasks runs on a chain of k organizations over A2A (one subtask per
# hop, the frameworks in turn), each on its framework's default limit only; does it finish without a limit stop?
CHAIN = ["langgraph", "adk", "crewai", "openai_agents", "autogen"]
COMPOSITION_SERVERS = {   # DynamicMCPBench's keyless servers (its manifests/local.json), pinned
    "wikipedia":   ("9863", '[uvx, --from, "wikipedia-mcp==2.0.1", wikipedia-mcp]'),
    "pubmed":      ("9865", '[npx, -y, "@cyanheads/pubmed-mcp-server@2.11.1"]'),
    "eurostat":    ("9866", '[npx, -y, "@cyanheads/eurostat-mcp-server@0.11.1"]'),
    "openlibrary": ("9867", '[npx, -y, "@cyanheads/openlibrary-mcp-server@0.4.0"]'),
}


def composition_config(k):
    orgs = [(f"org{i + 1}_{SHORT[CHAIN[i % len(CHAIN)]]}", CHAIN[i % len(CHAIN)]) for i in range(k)]
    servers = ", ".join(COMPOSITION_SERVERS)
    lines = []
    for i, (o, fw) in enumerate(orgs):
        if i < k - 1:
            role = (f"You are agent {i + 1} of a chain of {k} agents; the task has {k} subtasks. Do subtask {i + 1} "
                    "with your tools, then delegate the remaining subtasks to the next agent with your delegate tool, "
                    "passing on everything found so far. Then report the result you get back.")
        else:
            role = (f"You are the last agent of a chain of {k} agents; the task has {k} subtasks. Do the last "
                    "subtask with your tools and give the final result of the whole task.")
        lines.append(f"""  {o}:
    framework: {fw}
    agents:
      a: {{role: "{role}", mcp: [{servers}]}}""")
    links = "\n".join(f'  - "{a}.a -> {b}.a"' for (a, _), (b, _) in zip(orgs, orgs[1:]))
    mcp = "\n".join(f'  {n}: {{url: "http://127.0.0.1:{port}/mcp", command: {cmd}}}'
                     for n, (port, cmd) in COMPOSITION_SERVERS.items())
    return f"""# Per-agent limits do not compose. Tasks with {k} subtasks (DynamicMCPBench) on a chain of {k} organizations over A2A,
# one agent each in its own process, one subtask per hop, the frameworks in turn ({" -> ".join(CHAIN)} -> ...), each on
# its framework's default limit only (no limit for the whole request). Generated by make_pair_configs.py.
name: composition_k{k}
model: {{kind: openai-compatible, url: "http://127.0.0.1:11434/v1", model: "llama3.2:3b"}}
prices: {{usd_per_1m_input: 0.15, usd_per_1m_output: 0.60, usd_per_tool_call: 0.0}}
request_limit: {{max_depth: 100, deadline_s: 7200, max_cost_usd: 100.0}}   # attached, never enforced
tasks: {{dataset: dynamicmcpbench, servers: [{servers}], subtasks: {k}, n: 10}}
mcp_servers:
{mcp}
organizations:
{chr(10).join(lines)}
links:
{links}
entry: {orgs[0][0]}.a
"""

if __name__ == "__main__":
    n = 0
    for s, r in itertools.product(SENDERS, RECEIVERS):
        if FAMILY(s) == FAMILY(r):
            continue
        n += 1
        for folder, name, make in (("exp1", f"a2a_{s}_to_{r}.yaml", a2a_config), ("gaia_limits", f"gaia_{s}_to_{r}.yaml", gaia_config)):
            os.makedirs(os.path.join(HERE, "configs", folder), exist_ok=True)
            open(os.path.join(HERE, "configs", folder, name), "w").write(make(s, r))
    print(f"wrote {n} pairs into configs/exp1 and configs/gaia_limits")
    os.makedirs(os.path.join(HERE, "configs", "limit_checks"), exist_ok=True)
    for r in CHECKED:
        open(os.path.join(HERE, "configs", "limit_checks", f"check_{r}.yaml"), "w").write(check_config(r))
    print(f"wrote {len(CHECKED)} configs into configs/limit_checks")
    os.makedirs(os.path.join(HERE, "configs", "native_limits"), exist_ok=True)
    for fw, (_, _, values) in NATIVE.items():
        for v in values:
            open(os.path.join(HERE, "configs", "native_limits", f"native_{fw}_{v:03d}.yaml"), "w").write(native_config(fw, v))
    print(f"wrote {sum(len(v[2]) for v in NATIVE.values())} configs into configs/native_limits")
    os.makedirs(os.path.join(HERE, "configs", "composition"), exist_ok=True)
    for k in range(2, 6):
        open(os.path.join(HERE, "configs", "composition", f"k{k}.yaml"), "w").write(composition_config(k))
    print("wrote configs/composition/k2..k5.yaml")
